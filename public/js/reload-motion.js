/* =============================================================================
 *  reload-motion.js  -  1인칭 재장전 동작
 *
 *  총 모델에는 뼈대도 애니메이션도 들어 있지 않다. 그래서 탄창을 뽑는 손이나
 *  노리쇠가 따로 움직이지는 못한다. 대신 "총 전체가 어떻게 움직이는가"를
 *  손으로 적어 둔다. 실제 재장전에서 총이 하는 일은 이게 거의 전부다.
 *
 *    1. 총을 몸 쪽으로 당겨 내리고 탄창 구멍이 보이게 안쪽으로 기울인다
 *    2. 탄창 멈치를 눌러 빈 탄창을 떨어뜨린다  (탄창이 화면 아래로 떨어진다)
 *    3. 새 탄창을 밀어 넣는다                  (아래에서 위로 한 번 툭)
 *    4. 노리쇠를 당겼다 놓는다                 (뒤로 당겼다 앞으로 튄다)
 *    5. 원래 자세로 돌아온다
 *
 *  시간은 0~1 로 정규화한다. 총마다 재장전 시간이 다르므로(2.0~3.2초) 같은
 *  동작이 그 길이에 맞춰 늘어나고 줄어든다. 소리(audio.reload)도 같은 비율로
 *  네 박자를 찍으므로 손동작과 소리가 어긋나지 않는다.
 * ========================================================================== */

/* [t, 위치(오른쪽/위/앞), 회전(X 끄덕임/Y 좌우/Z 굴림)]
 * 위치는 미터, 회전은 라디안. 총은 화면 오른쪽 아래에 있으므로 "안쪽으로
 * 기울인다" = Y 를 음수로 돌린다. */
const KEYS = [
  [0.00, [0, 0, 0], [0, 0, 0]],
  [0.14, [-0.045, -0.085, 0.055], [0.30, -0.38, 0.24]],   // 당겨 내리고 기울인다
  [0.30, [-0.050, -0.095, 0.060], [0.34, -0.44, 0.28]],   // 멈치를 누른다 (탄창 낙하)
  [0.52, [-0.048, -0.090, 0.058], [0.33, -0.42, 0.27]],   // 새 탄창을 집어 온다
  [0.66, [-0.044, -0.062, 0.050], [0.27, -0.34, 0.20]],   // 밀어 넣는다 (위로 툭)
  [0.78, [-0.030, -0.050, 0.075], [0.20, -0.24, 0.13]],   // 노리쇠를 뒤로 당긴다
  [0.86, [-0.026, -0.044, 0.030], [0.16, -0.20, 0.10]],   // 놓으면 앞으로 튄다
  [1.00, [0, 0, 0], [0, 0, 0]],
];

/* 빈 탄창이 보이는 구간. 0.30 에 빠져서 0.62 쯤 화면 밖으로 사라진다. */
const MAG_OUT = 0.30;
const MAG_GONE = 0.62;

const smooth = (k) => k * k * (3 - 2 * k);

/**
 * 재장전 진행도 t(0~1) 에서의 총 자세.
 *
 * @returns {{ position: number[], rotation: number[], mag: null | {position:number[], spin:number} }}
 *          position/rotation 은 평소 자세에 "더할" 값이다.
 *          mag 는 떨어지는 빈 탄창(총 기준 위치). 없으면 null.
 */
export function reloadPose(t) {
  const k = Math.max(0, Math.min(1, Number(t) || 0));
  let i = 0;
  while (i < KEYS.length - 2 && k > KEYS[i + 1][0]) i++;
  const [t0, p0, r0] = KEYS[i];
  const [t1, p1, r1] = KEYS[i + 1];
  const f = smooth(t1 === t0 ? 0 : (k - t0) / (t1 - t0));
  const mix = (a, b) => [
    a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f, a[2] + (b[2] - a[2]) * f,
  ];
  return { position: mix(p0, p1), rotation: mix(r0, r1), mag: magPose(k) };
}

/**
 * 떨어지는 빈 탄창. 총 손잡이 아래에서 출발해 중력으로 떨어지면서 돈다.
 * 화면 좌표(카메라 기준)에서 계산하므로 고개를 돌려도 눈앞에서 떨어진다.
 */
function magPose(k) {
  if (k < MAG_OUT || k > MAG_GONE) return null;
  const s = (k - MAG_OUT) / (MAG_GONE - MAG_OUT);   // 0~1
  return {
    // 아래로 가속(중력), 살짝 뒤로 밀린다
    position: [-0.02 * s, -0.04 - 1.35 * s * s, 0.05 + 0.10 * s],
    spin: s * 3.4,
  };
}

/** 재장전 진행도. 끝났으면 1 을 넘는다. */
export function reloadProgress(now, startedAt, seconds) {
  const total = Math.max(0.2, Number(seconds) || 2.3);
  return (now - startedAt) / (total * 1000);
}
